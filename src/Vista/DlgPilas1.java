    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
         String buscado = txtElemento.getText().trim();

    if (buscado.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Escriba el elemento que desea buscar.",
            "Campo vacío",
            JOptionPane.WARNING_MESSAGE
        );

        txtElemento.requestFocus();
        return;
    }

    int posicion = 1;
    int filaEncontrada = -1;

    for (int i = pila.size() - 1; i >= 0; i--) {
        if (pila.get(i).equalsIgnoreCase(buscado)) {
            filaEncontrada = posicion - 1;
            break;
        }

        posicion++;
    }

    if (filaEncontrada >= 0) {
        tblPila.setRowSelectionInterval(
            filaEncontrada,
            filaEncontrada
        );

        JOptionPane.showMessageDialog(
            this,
            "Elemento encontrado en la posición "
                    + (filaEncontrada + 1)
                    + " desde la cima."
        );
    } else {
        tblPila.clearSelection();

        JOptionPane.showMessageDialog(
            this,
            "El elemento no se encuentra en la pila.",
            "No encontrado",
            JOptionPane.WARNING_MESSAGE
        );
    }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed
        String elemento = txtElemento.getText().trim();

    if (elemento.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Debe escribir un elemento.",
            "Campo vacío",
            JOptionPane.WARNING_MESSAGE
        );

        txtElemento.requestFocus();
        return;
    }

    pila.push(elemento);

    // Actualiza automáticamente la tabla
    mostrar();

    JOptionPane.showMessageDialog(
        this,
        "Elemento insertado correctamente."
    );

    txtElemento.setText("");
    txtElemento.requestFocus();
    }//GEN-LAST:event_btnInsertarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
      if (pila.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "No se puede eliminar porque la pila está vacía.",
            "Pila vacía",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String elementoCima = pila.peek();

    int respuesta = JOptionPane.showConfirmDialog(
        this,
        "¿Desea eliminar el elemento de la cima: "
                + elementoCima + "?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {
        String elementoEliminado = pila.pop();

        // Actualiza automáticamente la tabla
        mostrar();

        JOptionPane.showMessageDialog(
            this,
            "Elemento eliminado: " + elementoEliminado
        );

        txtElemento.setText("");
        txtElemento.requestFocus();
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

