private void mostrar() {
    modelo.setRowCount(0);

    int posicion = 1;

    for (int i = pila.size() - 1; i >= 0; i--) {
        modelo.addRow(new Object[]{
            posicion,
            pila.get(i)
        });

        posicion++;
    }
}
